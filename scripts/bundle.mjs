import { readFile, writeFile } from 'node:fs/promises';
const web = new URL('../web/', import.meta.url);
// These first-party modules have no external dependencies or dynamic imports.
export async function bundle() {
  const sources = await Promise.all(['mie.js', 'spheroid.js', 'geometry.js', 'app.js'].map(name => readFile(new URL(name, web), 'utf8')));
  const joined = sources.map(source => source.replace(/^import .*?;\r?\n/gm, '').replace(/^export /gm, '')).join('\n');
  await writeFile(new URL('app.bundle.js', web), `// Generated by scripts/bundle.mjs. Edit the source modules, not this file.\n(()=>{\n${joined}\n})();\n`);
}
if (process.argv[1] && new URL(process.argv[1], 'file:').href === import.meta.url) await bundle();
